"""Generate feathered wing geometry, atlas and an orthographic geometry preview."""
from pathlib import Path
from PIL import Image, ImageDraw
import random, math
ROOT=Path(__file__).resolve().parents[1]
random.seed(924)
im=Image.new('RGBA',(128,64),(0,0,0,0))
# Cuboid UV regions: warm pale feather, darker flight tips, warm shoulder bones.
for x0,x1,base in [(0,48,(220,204,173)),(48,96,(157,131,103)),(96,128,(113,88,70))]:
 for y in range(64):
  for x in range(x0,x1):
   n=random.randrange(-9,10)+(3 if x%4==0 else 0)
   im.putpixel((x,y),tuple(max(0,min(255,c+n)) for c in base)+(255,))
im.save(ROOT/'src/main/resources/assets/bunnidogs/textures/entity/bunnidog_wings.png')
parts=[]
# Each side has an upper arm and a folding outer hand. Feather cuboids overlap
# like shingles, with progressively swept, narrow tips rather than a flat rectangle.
for side in [-1,1]:
 name='left' if side==1 else 'right'
 def box(x,y,z,w,h,d,uv=0):
  if side<0:x=-x-w
  return f'.texOffs({uv},0).addBox({x}F,{y}F,{z}F,{w}F,{h}F,{d}F)'
 arm=box(0,-.5,-1,8,1,2,96)
 for i in range(7):arm+=box(i,-.3,-.3+i*.18,1.65,.6,5.5-i*.25)
 hand=box(0,-.4,-.8,8,.8,1.6,96)
 for i in range(9):hand+=box(i*.95,-.2,i*.3,1.4,.4,7.8-i*.55,48 if i>5 else 0)
 parts.append(f'        var {name}=body.addOrReplaceChild("{name}",CubeListBuilder.create(){arm},PartPose.offset({side*3.5}F,-2F,-1.7F));\n        {name}.addOrReplaceChild("hand",CubeListBuilder.create(){hand},PartPose.offset({side*7}F,0,0));')
s='''// Generated by art/gen_wings.py; separate appendages preserve the approved sculpt.
package com.bunnidogs.mod.client.model;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.*;
public final class BunnidogWingModelLayer {
    public static LayerDefinition createLayer() {
        var mesh=new MeshDefinition();
        var body=mesh.getRoot().addOrReplaceChild("body",CubeListBuilder.create(),BunnidogModelLayer.createBodyLayer().bakeRoot().getChild("body").getInitialPose());
'''+ '\n'.join(parts)+'''
        return LayerDefinition.create(mesh,128,64);
    }
}
'''
(ROOT/'src/main/java/com/bunnidogs/mod/client/model/BunnidogWingModelLayer.java').write_text(s)
# Preview the actual cuboid upper surfaces in the spread pose, plus atlas.
preview=Image.new('RGB',(1000,500),(42,47,54));dr=ImageDraw.Draw(preview)
dr.text((24,16),'Feathered wings - generated geometry / spread pose (top)',fill='white')
for side in [-1,1]:
 for i in range(7):
  x=side*(3.5+i);z=-1.7-.3+i*.18
  xa,xb=sorted([500+x*19,500+(x+side*1.65)*19]);dr.rectangle((xa,140+z*19,xb,140+(z+5.5-i*.25)*19),fill=(220-i*3,204-i*3,173-i*3),outline=(97,80,62))
 for i in range(9):
  x=side*(10.5+i*.95);z=-1.7+i*.3
  xa,xb=sorted([500+x*19,500+(x+side*1.4)*19]);dr.rectangle((xa,140+z*19,xb,140+(z+7.8-i*.55)*19),fill=(166,143,115) if i>5 else (220,204,173),outline=(97,80,62))
dr.ellipse((440,100,560,280),fill=(132,112,94),outline=(230,217,191))
preview.paste(im.resize((256,128)),(24,345));dr.text((300,360),'128 x 64 atlas; overlapping coverts and swept flight feathers',fill='white')
preview.save(ROOT/'art/wings_preview.png')

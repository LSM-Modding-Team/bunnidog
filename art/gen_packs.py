import json
import math
import numpy as np
from PIL import Image, ImageDraw, ImageFont
from gen_syringe import ROOT, RES

# Native model coordinates relative to the approved body's hip pivot (Y points down).
STRAPS=[]
for z,points in [(-.8,[(-4.3,-1.6),(-3,-2.8),(-1.4,-3.3),(1.4,-3.3),(3,-2.8),(4.3,-1.6)]),
                 (1.9,[(-3.7,-1.2),(-2.6,-2.4),(-1.2,-3),(1.2,-3),(2.6,-2.4),(3.7,-1.2)])]:
    for (x,y),(x2,y2) in zip(points,points[1:]):
        STRAPS.append(((0,-.15,-.325,math.hypot(x2-x,y2-y),.3,.65,40,0),(x,y,z),math.atan2(y2-y,x2-x)))
BAGS=[]
for z in (-1.6,1.0):
    for side in (1,-1):
        inset=.6 if z < 0 else 1.2
        BAGS.append([(4.4-inset if side > 0 else -6.8+inset,-2.6,z,2.4,3.5,2.3,0,0),
            (4.3-inset if side > 0 else -7.0+inset,-2.9,z-.1,2.7,.9,2.5,16,0),
            (6.8-inset if side > 0 else -7.1+inset,-1.6,z+.8,.3,1,.6,32,0)])


def java():
    def cubes(boxes):
        result='CubeListBuilder.create()'
        for x,y,z,w,h,d,u,v in boxes:
            values=', '.join(f'{float(n):g}F' for n in (x,y,z,w,h,d))
            result+=f'.texOffs({u},{v}).addBox({values})'
        return result
    parts='\n'.join(f'        body.addOrReplaceChild("bag_{i}",{cubes(boxes)},PartPose.ZERO);' for i,boxes in enumerate(BAGS))
    straps='\n'.join(f'        body.addOrReplaceChild("strap_{i}",{cubes([box])},PartPose.offsetAndRotation({x:g}F,{y:g}F,{z:g}F,0,0,{angle:g}F));'
        for i,(box,(x,y,z),angle) in enumerate(STRAPS))
    code='''// Generated by art/gen_packs.py. Equipment only; the approved sculpt is unchanged.
package com.bunnidogs.mod.client.model;

import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;

public final class BunnidogPackModelLayer {
    private BunnidogPackModelLayer() {}
    public static LayerDefinition createLayer() {
        var mesh = new MeshDefinition();
        var pivot = BunnidogModelLayer.createBodyLayer().bakeRoot().getChild("body").getInitialPose();
        var body = mesh.getRoot().addOrReplaceChild("body",CubeListBuilder.create(),pivot);
STRAPS
PARTS
        return LayerDefinition.create(mesh,64,32);
    }
}
'''.replace('STRAPS',straps).replace('PARTS',parts)
    path=ROOT/'src/main/java/com/bunnidogs/mod/client/model/BunnidogPackModelLayer.java'; path.write_text(code)


def texture():
    image=Image.new('RGBA',(64,32),(135,90,53,255)); d=ImageDraw.Draw(image)
    for y in range(32):
        for x in range(64):
            shift=((x*17+y*7)%7)-3
            image.putpixel((x,y),(135+shift,90+shift,53+shift,255))
    d.rectangle((16,0,30,12),fill=(104,66,39)); d.line((17,4,28,4),fill=(191,149,89))
    d.rectangle((32,0,38,10),fill=(201,153,72)); d.rectangle((34,2,35,5),fill=(103,69,39))
    d.rectangle((40,0,63,8),fill=(87,58,35)); d.line((41,1,62,1),fill=(158,114,68))
    for x in (1,7): d.line((x,3,x,6),fill=(187,145,89))
    path=RES/'assets/bunnidogs/textures/entity/bunnidog_packs.png'; image.save(path)
    return image


def pack_faces(count, build, leg, baby):
    if count == 0: return []
    from preview_bunnidog import PARTS
    from sculpt_bunnidog import HIP_HEIGHT
    pivot=np.asarray(next(p['pivot'] for p in PARTS if p['name']=='body'),dtype=float)
    scale=np.array([build,1+(build-1)*.6,1+(build-1)*.3]); lift=HIP_HEIGHT*(leg-1)
    faces=[]
    objects=STRAPS+[(box,(0,0,0),0) for box in sum(BAGS[:count],[])]
    for (x,y,z,w,h,d,u,v),offset,angle in objects:
        # Convert the native Y-down cube to the sculpt's Y-up coordinates.
        lo=np.array([x,-y-h,z]); hi=np.array([x+w,-y,z+d])
        x0,y0,z0=lo; x1,y1,z1=hi
        quads=[([(x1,y0,z1),(x1,y1,z1),(x1,y1,z0),(x1,y0,z0)],(u+d+w,v+d),(d,h)),
            ([(x0,y0,z0),(x0,y1,z0),(x0,y1,z1),(x0,y0,z1)],(u,v+d),(d,h)),
            ([(x0,y1,z1),(x0,y0,z1),(x1,y0,z1),(x1,y1,z1)],(u+d+w+d,v+d),(w,h)),
            ([(x1,y1,z0),(x1,y0,z0),(x0,y0,z0),(x0,y1,z0)],(u+d,v+d),(w,h)),
            ([(x0,y1,z0),(x1,y1,z0),(x1,y1,z1),(x0,y1,z1)],(u+d,v),(w,d)),
            ([(x0,y0,z1),(x1,y0,z1),(x1,y0,z0),(x0,y0,z0)],(u+d+w,v),(w,d))]
        for points,uv,size in quads:
            c,s=math.cos(angle),math.sin(angle); rotation=np.asarray([[c,s,0],[-s,c,0],[0,0,1]])
            translation=np.asarray([offset[0],-offset[1],offset[2]])
            raw=np.asarray(points)@rotation.T+translation
            center=(lo+hi)/2@rotation.T+translation
            corners=raw*scale+pivot; corners[:,1]+=lift
            if baby: corners*=.65
            normal=np.cross(corners[2]-corners[0],corners[3]-corners[1]); normal/=np.linalg.norm(normal)
            if normal @ (raw.mean(axis=0)-center) < 0:
                corners=corners[[0,3,2,1]]; normal=-normal
            faces.append((corners,normal,(uv[0],uv[1]+512),size,np.tile(normal,(4,1))))
    return faces


def preview(atlas):
    from preview_bunnidog import world_faces, render
    combined=Image.new('RGB',(512,544)); combined.paste(Image.open(RES/'assets/bunnidogs/textures/entity/bunnidog_tan.png').convert('RGB'),(0,0))
    combined.paste(atlas.convert('RGB'),(0,512)); tex=np.asarray(combined,dtype=float)
    canvas=Image.new('RGB',(1440,650),(239,235,226)); d=ImageDraw.Draw(canvas)
    font=ImageFont.truetype('DejaVuSans.ttf',18)
    for i,(count,build,leg,baby,yaw,label) in enumerate([(1,1,1,False,45,'One native bundle'),
            (4,1.6,1,False,135,'Chonker carrying four'),(3,.7,1.35,False,-55,'Smaller build retains existing cargo')]):
        faces=world_faces(build_scale=build,leg_scale=leg,baby=baby)
        faces+=pack_faces(count,build,leg,baby)
        tile=render(faces,tex,yaw=yaw,elevation=12,width=480,height=570,zoom=25)
        canvas.paste(tile,(480*i,45)); d.text((480*i+15,610),label,font=font,fill=(66,55,40))
    d.text((18,12),'Native bundle panniers on the actual approved sculpt; equipment is a separate material',font=font,fill=(66,55,40))
    canvas.save(ROOT/'art/bunnidog_packs_preview.png')


